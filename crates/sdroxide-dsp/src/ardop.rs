/// The control frame types. These carry no CRC, so only a strong leader and a
/// clean header let one through.
pub const CONTROL: [u8; 23] = [
    0x23, 0x24, 0x29, 0x2C, 0x2D, 0x2E, 0x30, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39,
    0x3A, 0x3B, 0x3C, 0x3D, 0x3E, 0x00, 0x2B,
];

/// A frame type's data mode. The odd frame type is the same mode with the ARQ
/// sequence bit set (`ardopcf` masks it before lookup).
pub fn mode_of(ftype: u8) -> Option<Mode> {
    MODES.iter().copied().find(|m| m.ftype == (ftype & 0xFE))
}

pub fn is_control(ftype: u8) -> bool {
    // ACKs are 0xE0–0xFF and NAKs 0x00–0x1F; the named control frames are the
    // rest of the small values.
    ftype >= 0xE0 || ftype <= 0x1F || CONTROL.contains(&ftype)
}

// ---------------------------------------------------------------- CRC-16
//
// `ardopcf`'s `GenCRC16`: MSB-first, initial 0xFFFF, constant 0x8810, each data
// bit fed into the low end of the register. This is *not* CRC-16-CCITT; the
// constant is what reproduces the reference, and the two check values below are
// from its own documentation.
pub fn crc16(data: &[u8]) -> u16 {
    let mut reg: u16 = 0xFFFF;
    for &byte in data {
        let mut mask = 0x80u8;
        for _ in 0..8 {
            let bit = byte & mask;
            mask >>= 1;
            let msb = reg & 0x8000;
            reg = (reg << 1) | if bit != 0 { 1 } else { 0 };
            if msb != 0 {
                reg ^= 0x8810;
            }
        }
    }
    reg
}

// ---------------------------------------------------------------- GF(256) / RS
//
// GF(2^8), primitive polynomial 0x11D, generator alpha = 2, first consecutive
// root alpha^1 (FCR = 1), systematic code with the parity at the tail.

struct Gf {
    exp: [u8; 512],
    log: [u8; 256],
}

impl Gf {
    fn new() -> Self {
        let mut exp = [0u8; 512];
        let mut log = [0u8; 256];
        let mut x: u16 = 1;
        for i in 0..255 {
            exp[i] = x as u8;
            log[x as usize] = i as u8;
            x <<= 1;
            if x & 0x100 != 0 {
                x ^= 0x11D;
            }
        }
        for i in 255..512 {
            exp[i] = exp[i - 255];
        }
        Gf { exp, log }
    }

    fn mul(&self, a: u8, b: u8) -> u8 {
        if a == 0 || b == 0 {
            0
        } else {
            self.exp[self.log[a as usize] as usize + self.log[b as usize] as usize]
        }
    }

    fn inv(&self, a: u8) -> u8 {
        // alpha^(255 - log a)
        self.exp[(255 - self.log[a as usize] as usize) % 255]
    }
}

/// The generator polynomial for `rslen` parity bytes, leading coefficient first
/// (monic). The first bytes for each length used by ARDOP are pinned in the
/// tests against the reference's own table.
#[cfg_attr(not(test), allow(dead_code))]
fn rs_generator(gf: &Gf, rslen: usize) -> Vec<u8> {
    let mut g = vec![1u8];
    for i in 0..rslen {
        let root = gf.exp[i + 1];
        let mut ng = vec![0u8; g.len() + 1];
        for j in 0..g.len() {
            ng[j] ^= gf.mul(g[j], root);
            ng[j + 1] ^= g[j];
        }
        g = ng;
    }
    g.reverse();
    g
}

/// Systematic RS encode, written the way `ardopcf`'s `librs` does it: the
/// 255-byte block is zero-padded in front of the short message, the feedback
/// shift register runs from the highest block position down, and the parity
/// comes out lowest-degree first. That byte order is not the textbook
/// leading-coefficient first one, and it is why a parity comparison against the
/// reference is part of the tests.
pub fn rs_encode(data: &[u8], rslen: usize) -> Vec<u8> {
    let gf = Gf::new();
    let nn = 255usize;
    let kk = nn - rslen;
    let g = rs_generator_asc(&gf, rslen);
    let mut pad = vec![0u8; nn];
    for (i, &b) in data.iter().enumerate() {
        pad[i + kk - data.len()] = b;
    }
    let mut bb = vec![0u8; rslen];
    for i in (0..kk).rev() {
        let fb = gf.log[(pad[i] ^ bb[rslen - 1]) as usize] as i32;
        if fb >= 0 {
            for j in (1..rslen).rev() {
                bb[j] = bb[j - 1]
                    ^ if g[j] == 0 {
                        0
                    } else {
                        gf.exp[gf.log[g[j] as usize] as usize + fb as usize]
                    };
            }
            bb[0] = gf.exp[gf.log[g[0] as usize] as usize + fb as usize];
        } else {
            for j in (1..rslen).rev() {
                bb[j] = bb[j - 1];
            }
            bb[0] = 0;
        }
    }
    let mut out = data.to_vec();
    out.extend_from_slice(&bb);
    out
}

/// The generator polynomial with ascending coefficients, as `gen_polys` builds
/// it before converting to index form.
fn rs_generator_asc(gf: &Gf, rslen: usize) -> Vec<u8> {
    let mut g = vec![0u8; rslen + 1];
    g[0] = 2;
    g[1] = 1;
    for i in 2..=rslen {
        g[i] = 1;
        for j in (1..i).rev() {
            g[j] = if g[j] != 0 {
                g[j - 1] ^ gf.exp[gf.log[g[j] as usize] as usize + i]
            } else {
                g[j - 1]
            };
        }
        g[0] = gf.exp[gf.log[g[0] as usize] as usize + i];
    }
    g
}

/// Syndromes of a codeword (highest-degree coefficient first): `S_i = c(αⁱ)`.
fn rs_syndromes(gf: &Gf, cw: &[u8], rslen: usize) -> Vec<u8> {
    (1..=rslen)
        .map(|i| {
            let a = gf.exp[i];
            let mut s = 0u8;
            for &b in cw {
                s = gf.mul(s, a) ^ b;
            }
            s
        })
        .collect()
}

fn poly_eval_asc(gf: &Gf, p: &[u8], x: u8) -> u8 {
    let mut y = 0u8;
    for &c in p.iter().rev() {
        y = gf.mul(y, x) ^ c;
    }
    y
}

fn poly_scale(gf: &Gf, p: &[u8], s: u8) -> Vec<u8> {
    p.iter().map(|&c| gf.mul(c, s)).collect()
}

fn poly_add(a: &[u8], b: &[u8]) -> Vec<u8> {
    let n = a.len().max(b.len());
    let mut out = vec![0u8; n];
    for i in 0..n {
        out[i] = a.get(i).copied().unwrap_or(0) ^ b.get(i).copied().unwrap_or(0);
    }
    out
}

/// Reed–Solomon decode: corrects up to `rslen/2` byte errors. Returns the
/// corrected codeword, or `None` if the syndromes cannot be cleared.
pub fn rs_decode(cw: &[u8], rslen: usize) -> Option<Vec<u8>> {
    let gf = Gf::new();
    let synd = rs_syndromes(&gf, cw, rslen);
    if synd.iter().all(|&s| s == 0) {
        return Some(cw.to_vec());
    }
    // Berlekamp–Massey, error locator in ascending order (constant first).
    let mut err = vec![1u8];
    let mut old = vec![1u8];
    for i in 0..rslen {
        let mut delta = synd[i];
        for j in 1..err.len() {
            if j <= i {
                delta ^= gf.mul(err[j], synd[i - j]);
            }
        }
        old.insert(0, 0);
        if delta != 0 {
            if old.len() > err.len() {
                let new = poly_scale(&gf, &old, delta);
                old = poly_scale(&gf, &err, gf.inv(delta));
                err = new;
            }
            err = poly_add(&err, &poly_scale(&gf, &old, delta));
        }
    }
    while err.len() > 1 && *err.last().unwrap() == 0 {
        err.pop();
    }
    let errors = err.len() - 1;
    if errors == 0 || errors * 2 > rslen {
        return None;
    }
    // Chien search: position i from the start has X = alpha^(n-1-i).
    let n = cw.len();
    let mut positions = Vec::new();
    for i in 0..n {
        let xi = gf.exp[(n - 1 - i) % 255];
        let xinv = gf.inv(xi);
        if poly_eval_asc(&gf, &err, xinv) == 0 {
            positions.push((i, xi));
        }
    }
    if positions.len() != errors {
        return None;
    }
    // Error evaluator: Omega(x) = S(x)*Lambda(x) mod x^rslen.
    let mut omega = vec![0u8; rslen];
    for i in 0..rslen {
        for j in 0..=i.min(err.len() - 1) {
            if i - j < synd.len() {
                omega[i] ^= gf.mul(synd[i - j], err[j]);
            }
        }
    }
    // Derivative of Lambda, ascending.
    let mut deriv = vec![0u8; err.len().saturating_sub(1)];
    for i in 1..err.len() {
        deriv[i - 1] = if i % 2 == 1 { err[i] } else { 0 };
    }
    let mut out = cw.to_vec();
    for &(pos, xi) in &positions {
        let xinv = gf.inv(xi);
        let den = poly_eval_asc(&gf, &deriv, xinv);
        if den == 0 {
            return None;
        }
        let num = poly_eval_asc(&gf, &omega, xinv);
        // FCR = 1: e = X^(1-FCR) * Omega(X^-1) / Lambda'(X^-1), exponent 0.
        let mag = gf.mul(num, gf.inv(den));
        out[pos] ^= mag;
    }
    if rs_syndromes(&gf, &out, rslen).iter().any(|&s| s != 0) {
        return None;
    }
    Some(out)
}

/// Correct a transmitted block (`data | parity`, ardopcf's byte order).
///
/// The reference stores the systematic codeword **lowest degree first**: its
/// `rs_correct` right-aligns the whole block at the top of the 255-coefficient
/// polynomial, so the parity sits *above* the message. Reversing the block puts
/// it in the highest-coefficient-first form the syndrome decoder works in, and
/// the zeros the shortening drops at the low end do not change divisibility.
fn rs_correct_block(block: &[u8], rslen: usize) -> Option<Vec<u8>> {
    let mut cw = block.to_vec();
    cw.reverse();
    let fixed = rs_decode(&cw, rslen)?;
    let mut out = fixed;
    out.reverse();
    Some(out)
}

// ---------------------------------------------------------------- the receiver

/// One decoded frame.
#[derive(Clone, Debug, PartialEq)]
pub struct Frame {
    pub ftype: u8,
    /// `None` for a control frame; the payload for a data frame.
    pub data: Option<Vec<u8>>,
    /// The normalised leader correlation that found it.
    pub confidence: f32,
}

/// The leader as the transmitter sends it: 12 two-tone 20 ms symbols with
/// alternating sign and the last one inverted.
pub fn leader() -> Vec<f32> {
    let mut out = Vec::with_capacity(LEAD_LEN);
    let nsym = LEAD_SYMBOLS;
    let mut sign = if nsym & 1 != 0 { -1.0f32 } else { 1.0 };
    for i in 0..nsym {
        let s = if i == nsym - 1 { -sign } else { sign };
        for n in 0..LEAD_SPS {
            let t = n as f64 / SR;
            // The reference's own template is the *difference* of the two
            // tones, not the sum (ardopSampleArrays.c, checked sample for
            // sample). The sign alternation is the same either way; the shape is
            // not, and a sum template correlates at 0.
            let v = (std::f64::consts::TAU * 1475.0 * t).sin()
                - (std::f64::consts::TAU * 1525.0 * t).sin();
            out.push(s * v as f32);
        }
        sign = -sign;
    }
    out
}

/// The frame type as the transmitter sends it: two identical bytes, each four
/// 4-FSK dibits MS-first plus an XOR parity symbol, signs alternating.
pub fn frametype_wave(ftype: u8) -> Vec<f32> {
    let tones = FSK50;
    let mut out = Vec::with_capacity(TYPE_LEN);
    let mut sym = 0usize;
    for _ in 0..2 {
        for k in 0..5 {
            let val = if k < 4 { (ftype >> (2 * (3 - k))) & 3 } else { type_parity(ftype) };
            let s = if sym % 2 == 0 { 1.0f32 } else { -1.0 };
            for n in 0..LEAD_SPS {
                let t = n as f64 / SR;
                out.push(s * (std::f64::consts::TAU * tones[val as usize] * t).sin() as f32);
            }
            sym += 1;
        }
    }
    out
}

fn type_parity(byte: u8) -> u8 {
    // ardopcf's ComputeTypeParity starts the running XOR at 1, not 0; the
    // recorded headers only check when that is kept (0x40 has parity 0, not 1).
    let mut p = 1u8;
    for k in 0..4 {
        p ^= (byte >> (2 * k)) & 3;
    }
    p
}

/// What one pass over a buffer found.
///
/// `decode_all` walks a whole recording with this; a live receiver calls it on a
/// buffer it owns and uses `safe` to drop what can no longer be part of a frame.
/// A `find_leader` sweep is the expensive part of this decoder, so the "nothing
/// here yet" answer has to say how far it looked or a stream would re-scan the
/// same audio on every block.
pub enum Scan {
    /// A frame, and how many samples from the front of the buffer it used.
    Frame { frame: Frame, used: usize },
    /// No whole frame yet. `safe` samples at the front cannot contain the start
    /// of one — but keep everything after them, because a leader may be sitting
    /// there waiting for its body.
    Nothing { safe: usize },
}

/// Decode the first frame in `audio` (12 kHz mono), or say how far it is safe to
/// drop.
pub fn scan(audio: &[f32]) -> Scan {
    let mut start = 0usize;
    while let Some(pos) = find_leader(&audio[start..]) {
        let at = start + pos;
        let mut found: Option<(usize, u8, f32, Option<Vec<u8>>)> = None;
        let mut fallback: Option<(usize, u8, f32)> = None;
        // A header is 10 symbols, and the leader's last symbol can imitate one
        // 120 samples early, so every candidate start that passes the type
        // check is tried against the body and the CRC is the arbiter.
        for extra in (0..=5 * LEAD_SPS).step_by(5) {
            let hstart = at + 11 * LEAD_SPS + extra;
            if hstart + TYPE_LEN > audio.len() {
                // The leader is real but its header is not all here yet.
                return Scan::Nothing { safe: at };
            }
            let (ftype, conf) = read_type(&audio[hstart..hstart + TYPE_LEN]);
            let Some(ft) = ftype else { continue };
            if mode_of(ft).is_none() && !is_control(ft) {
                continue;
            }
            // A frame whose body has not all arrived cannot be judged: not
            // having the audio is not the same as failing the CRC, and a stream
            // reaches this boundary on every frame it hears.
            if let Some(mode) = mode_of(ft)
                && hstart + TYPE_LEN + body_len(mode) > audio.len()
            {
                return Scan::Nothing { safe: at };
            }
            if fallback.is_none() {
                fallback = Some((hstart, ft, conf));
            }
            let data = if is_control(ft) {
                None
            } else {
                mode_of(ft).and_then(|mode| {
                    for implicit in [true, false] {
                        for i in 0..13 {
                            let off = (i as isize - 6) * 4;
                            if let Some(d) =
                                decode_body(&audio[hstart + TYPE_LEN..], off, mode, ft, implicit)
                            {
                                return Some(d);
                            }
                        }
                    }
                    None
                })
            };
            if let Some(d) = data {
                found = Some((hstart, ft, conf, Some(d)));
                break;
            }
        }
        let (hstart, ft, conf, data) = match found {
            Some(f) => f,
            None => match fallback {
                Some((h, ft, c)) => (h, ft, c, None),
                None => {
                    start = at + LEAD_LEN;
                    continue;
                }
            },
        };
        // A data mode whose body failed is still reported with no data, so the
        // caller can NAK it; a control type is reported as itself.
        let used = hstart + TYPE_LEN + mode_of(ft).map(body_len).unwrap_or(0);
        return Scan::Frame { frame: Frame { ftype: ft, data, confidence: conf }, used };
    }
    Scan::Nothing { safe: audio.len().saturating_sub(LEAD_LEN.saturating_sub(1)) }
}

/// Decode every frame in `audio` (12 kHz mono), leftmost first.
pub fn decode_all(audio: &[f32]) -> Vec<Frame> {
    let mut out = Vec::new();
    let mut at = 0usize;
    while at < audio.len() {
        match scan(&audio[at..]) {
            Scan::Frame { frame, used } => {
                out.push(frame);
                at += used.max(1);
            }
            Scan::Nothing { .. } => break,
        }
    }
    out
}

/// The live ARDOP receiver: a rolling buffer and [`scan`], so the expensive
/// leader search only ever sees audio it has not already looked at.
///
/// There is no tuning here and no symbol clock to find: an ARDOP frame carries
/// its own leader, its frame type and its CRC, and the carrier grid is fixed
/// around 1500 Hz of audio — which is why the mode is a fixed-centre one.
pub struct ArdopReceiver {
    buf: Vec<f32>,
    mag: f32,
}

/// How much audio is kept while frames are being resolved. A frame is at most
/// about two seconds; anything older than this without a frame in it is a false
/// leader and is dropped rather than remembered.
const KEEP_S: f64 = 6.0;

impl Default for ArdopReceiver {
    fn default() -> Self {
        Self::new()
    }
}

impl ArdopReceiver {
    pub fn new() -> Self {
        ArdopReceiver { buf: Vec::new(), mag: 0.0 }
    }

    pub fn magnitude(&self) -> f32 {
        self.mag
    }

    /// Forget any partial frame — the operator retuned, so it is not ours.
    pub fn reset(&mut self) {
        self.buf.clear();
        self.mag = 0.0;
    }

    /// Feed 12 kHz audio; returns every frame completed by it.
    pub fn process(&mut self, audio: &[f32]) -> Vec<Frame> {
        let peak = audio.iter().fold(0.0f32, |m, s| m.max(s.abs()));
        self.mag += 0.02 * (peak - self.mag);
        self.buf.extend_from_slice(audio);
        let mut out = Vec::new();
        loop {
            match scan(&self.buf) {
                Scan::Frame { frame, used } => {
                    out.push(frame);
                    self.buf.drain(..used.min(self.buf.len()));
                    if self.buf.is_empty() {
                        break;
                    }
                }
                Scan::Nothing { safe } => {
                    if safe > 0 {
                        self.buf.drain(..safe.min(self.buf.len()));
                    }
                    break;
                }
            }
        }
        let keep = (KEEP_S * SR) as usize;
        if self.buf.len() > keep {
            let drop = self.buf.len() - keep;
            self.buf.drain(..drop);
        }
        out
    }
}

/// What to call a frame type in a log: the data mode's name, or its number when
/// it is a control frame. The control frames' own names are in `ardopcf`'s
/// `FrameInfo` table, which this port does not carry yet.
pub fn frame_name(ftype: u8) -> String {
    match mode_of(ftype) {
        Some(m) => m.name.to_string(),
        None if ftype >= 0xE0 => "ACK".to_string(),
        None if ftype <= 0x1F => "NAK".to_string(),
        None => format!("ctrl {ftype:#04x}"),
    }
}

/// How many samples a mode's body occupies.
fn body_len(mode: Mode) -> usize {
    if mode.kind == 3 {
        let sps = (SR as usize) / mode.fsk_baud as usize;
        mode.block() * 4 * sps
    } else {
        let (bps, _) = BPS[mode.kind as usize];
        (mode.block() * 8 / bps + 1) * PSK_SPS
    }
}

/// One-shot: the first frame in the audio.
pub fn decode_frame(audio: &[f32]) -> Option<Frame> {
    decode_all(audio).into_iter().next()
}

/// Find the leader by normalised cross-correlation. Returns the sample offset of
/// the leader's first sample.
fn find_leader(audio: &[f32]) -> Option<usize> {
    let lead = leader();
    let n = lead.len();
    if audio.len() < n {
        return None;
    }
    let lead_e: f64 = lead.iter().map(|&v| (v as f64) * (v as f64)).sum();
    let ncc_at = |i: usize, energy: f64| -> f32 {
        let mut corr = 0.0f64;
        for (k, &l) in lead.iter().enumerate() {
            corr += audio[i + k] as f64 * l as f64;
        }
        (corr.abs() / (energy.max(1e-9) * lead_e).sqrt()) as f32
    };
    // Coarse scan, then refine around the best candidate: the leader is 2880
    // samples and the audio is short, so this is cheap and does not depend on
    // the correlation's local shape.
    let mut best = (0.0f32, 0usize);
    let mut energy: f64 = audio[..n].iter().map(|&v| (v as f64) * (v as f64)).sum();
    for i in 0..=audio.len() - n {
        if i > 0 {
            let old = audio[i - 1] as f64;
            let new = audio[i + n - 1] as f64;
            energy += new * new - old * old;
        }
        let c = ncc_at(i, energy);
        if c > best.0 {
            best = (c, i);
        }
    }
    if best.0 < 0.65 {
        return None;
    }
    let lo = best.1.saturating_sub(LEAD_SPS);
    let hi = (best.1 + LEAD_SPS).min(audio.len().saturating_sub(n));
    for i in lo..=hi {
        let energy: f64 = audio[i..i + n].iter().map(|&v| (v as f64) * (v as f64)).sum();
        let c = ncc_at(i, energy);
        if c > best.0 {
            best = (c, i);
        }
    }
    Some(best.1)
}

/// Read the two 4-FSK frame-type bytes and their parity symbols.
fn read_type(header: &[f32]) -> (Option<u8>, f32) {
    if header.len() < TYPE_LEN {
        return (None, 0.0);
    }
    let mut syms = [0u8; TYPE_SYMBOLS];
    let mut conf = 0.0f32;
    for (s, slot) in syms.iter_mut().enumerate() {
        let seg = &header[s * LEAD_SPS..(s + 1) * LEAD_SPS];
        let (tone, c) = strongest_tone(seg, &FSK50);
        *slot = tone as u8;
        conf += c;
    }
    conf /= TYPE_SYMBOLS as f32;
    let b0 = (syms[0] << 6) | (syms[1] << 4) | (syms[2] << 2) | syms[3];
    let b1 = (syms[5] << 6) | (syms[6] << 4) | (syms[7] << 2) | syms[8];
    if b0 == b1 && syms[4] == type_parity(b0) && syms[9] == type_parity(b1) {
        (Some(b0), conf)
    } else {
        (None, conf)
    }
}

/// Non-coherent tone detection over one symbol: magnitude at each tone.
fn strongest_tone(seg: &[f32], tones: &[f64; 4]) -> (usize, f32) {
    let mut best = (0usize, 0.0f64);
    for (t, &f) in tones.iter().enumerate() {
        let (mut re, mut im) = (0.0f64, 0.0f64);
        for (n, &v) in seg.iter().enumerate() {
            let w = std::f64::consts::TAU * f * n as f64 / SR;
            re += v as f64 * w.cos();
            im -= v as f64 * w.sin();
        }
        let m = re.hypot(im);
        if m > best.1 {
            best = (t, m);
        }
    }
    (best.0, best.1 as f32)
}

/// Decode one data body at a symbol-start offset (in samples, may be negative).
fn decode_body(
    after_header: &[f32],
    offset: isize,
    mode: Mode,
    ftype: u8,
    implicit: bool,
) -> Option<Vec<u8>> {
    let mut payload = Vec::new();
    for c in 0..mode.carriers {
        let block = if mode.kind == 3 {
            demod_4fsk(after_header, offset, mode, c)?
        } else {
            demod_psk(after_header, offset, mode, c, implicit)?
        };
        // The codeword is systematic, so a clean payload validates before the
        // parity is touched; only a failed CRC is worth the RS decode.
        let d = mode.data_len;
        let check = |b: &[u8]| {
            let crc = crc16(&b[..d + 1]);
            b[d + 1] == (crc >> 8) as u8 && b[d + 2] == ((crc & 0xFF) as u8 ^ (ftype & 0xFF))
        };
        let block = if check(&block) {
            block
        } else {
            let fixed = rs_correct_block(&block, mode.rs_len)?;
            if !check(&fixed) {
                return None;
            }
            fixed
        };
        let count = (block[0] as usize).min(d);
        payload.extend_from_slice(&block[1..1 + count]);
    }
    Some(payload)
}

/// The 4-FSK body: `carriers * block * 8 / 2` symbols at 50 or 100 baud.
fn demod_4fsk(audio: &[f32], offset: isize, mode: Mode, _carrier: usize) -> Option<Vec<u8>> {
    let baud = mode.fsk_baud as usize;
    let sps = SR as usize / baud;
    let tones = if baud == 50 { &FSK50 } else { &FSK100 };
    let bytes = mode.block();
    let symbols = bytes * 4; // two bits per symbol
    let base = offset; // one carrier for every 4-FSK mode
    let mut bits = Vec::with_capacity(bytes * 8);
    for s in 0..symbols {
        let start = base + (s * sps) as isize;
        let seg = slice_at(audio, start, sps)?;
        let (tone, _) = strongest_tone(seg, tones);
        bits.push(((tone >> 1) & 1) as u8);
        bits.push((tone & 1) as u8);
    }
    Some(pack_bits(&bits))
}

/// The PSK/QAM body for one carrier: one reference symbol then the data.
fn demod_psk(
    audio: &[f32],
    offset: isize,
    mode: Mode,
    carrier: usize,
    implicit: bool,
) -> Option<Vec<u8>> {
    let (bps, symset) = BPS[mode.kind as usize];
    let idx = match mode.carriers {
        1 => PSK_CAR[0],
        2 => PSK_CAR[1],
        4 => PSK_CAR[2],
        _ => PSK_CAR[3],
    };
    let freq = PSK_GRID[idx[carrier]];
    let block = mode.block();
    let symbols = block * 8 / bps + 1; // + the phase reference
    let base = offset + 0;
    let mut phases = Vec::with_capacity(symbols);
    let mut mags = Vec::with_capacity(symbols);
    for s in 0..symbols {
        let start = base + (s * PSK_SPS) as isize;
        let seg = slice_at(audio, start, PSK_SPS)?;
        let (mut re, mut im) = (0.0f64, 0.0f64);
        for (n, &v) in seg.iter().enumerate() {
            let env = (std::f64::consts::PI * n as f64 / (PSK_SPS - 1) as f64).sin();
            let w = std::f64::consts::TAU * freq * n as f64 / SR;
            re += v as f64 * env * w.cos();
            im -= v as f64 * env * w.sin();
        }
        // The transmitted shape is a sine, and the matched filter is a complex
        // exponential: the recovered angle is the symbol phase minus pi/2.
        let phase = (im.atan2(re) + std::f64::consts::FRAC_PI_2) / (std::f64::consts::PI / 4.0);
        phases.push((phase.round() as i32).rem_euclid(8) as u8);
        mags.push(re.hypot(im));
    }
    let full = mags[0].max(1e-9);
    let mut bits = Vec::with_capacity(block * 8);
    let first = if implicit { 0 } else { 1 };
    let mut prev_phase = if implicit { 0 } else { phases[0] };
    for s in first..symbols {
        let inc = phases[s].wrapping_sub(prev_phase) & 7;
        prev_phase = phases[s];
        let mut byt = (inc / symset as u8) as u8;
        if mode.kind == 2 && mags[s] < 0.7 * full {
            byt |= 8;
        }
        for k in (0..bps).rev() {
            bits.push((byt >> k) & 1);
        }
    }
    if bits.len() < block * 8 {
        return None;
    }
    bits.truncate(block * 8);
    let bytes = pack_bits(&bits);
    if std::env::var("ARDOP_TRACE").is_ok() {
        eprintln!("car {carrier} f {freq} bytes {:02X?}", &bytes[..bytes.len().min(16)]);
    }
    Some(bytes)
}

fn slice_at(audio: &[f32], start: isize, len: usize) -> Option<&[f32]> {
    if start < 0 || start as usize + len > audio.len() {
        return None;
    }
    Some(&audio[start as usize..start as usize + len])
}

fn pack_bits(bits: &[u8]) -> Vec<u8> {
    bits.chunks(8).map(|c| c.iter().fold(0u8, |v, &b| (v << 1) | b)).collect()
}

