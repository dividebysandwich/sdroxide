//! ARDOP — the native OFDM/4FSK HF data protocol, receive side.
//!
//! Written from the protocol description at
//! `patrick.lidstone.net/ardop-native-ofdm-4fsk-hf-arq-data-protocol/`, which is
//! a clean-room transcription of the MIT `ardopcf` reference (Rick Muething
//! KN6KB, John Wiseman G8BPQ, Peter LaRue AI7YN). `ardopcf` is credited in the
//! README's Acknowledgements; the constant tables here (frame types, tone plans,
//! carrier grid, GF(2⁸) polynomial) are protocol facts.
//!
//! Only the **modem** is here: leader, frame-type header, and the data body in
//! its PSK/QAM and 4-FSK forms, with the per-carrier Reed–Solomon + keyed CRC.
//! The ARQ state machine and the TNC host protocol are separate layers and are
//! not part of this port.
//!
//! A frame is three fixed pieces ([`FRAME`] has the numbers):
//!
//! * **leader** — 1475 + 1525 Hz in 12 alternating 20 ms symbols, the last one
//!   inverted; the matched filter is the whole waveform.
//! * **frame type** — two 4-FSK bytes at 50 baud, each four dibits plus an XOR
//!   parity symbol; both copies must agree.
//! * **body** — 1..8 carriers at 100 baud with a half-sine envelope, phase
//!   differential per carrier, one 4-PSK/8-PSK/16-QAM symbol per 120 samples;
//!   or one 4-FSK carrier at 50/100 baud. Each carrier carries
//!   `count | data | CRC-16 | RS parity`.
//!
//! **The gate is a recording made by `ardopcf` itself**, in `samples/ardop/`,
//! not a loopback: 4PSK one carrier, 16QAM eight carriers, 4FSK at 100 baud and
//! a ConReq control frame, each generated by the reference from a known string.

// ---------------------------------------------------------------- constants

/// Modem sample rate. Everything below is defined at this rate.
pub const SR: f64 = 12_000.0;
const LEAD_SPS: usize = 240;
const LEAD_SYMBOLS: usize = 12;
pub const LEAD_LEN: usize = LEAD_SPS * LEAD_SYMBOLS;
const TYPE_SYMBOLS: usize = 10;
pub const TYPE_LEN: usize = TYPE_SYMBOLS * LEAD_SPS;
/// Leader plus frame type: where a body starts.
pub const HEADER_LEN: usize = LEAD_LEN + TYPE_LEN;

const FSK50: [f64; 4] = [1425.0, 1475.0, 1525.0, 1575.0];
const FSK100: [f64; 4] = [1350.0, 1450.0, 1550.0, 1650.0];
const PSK_SPS: usize = 120;
const PSK_GRID: [f64; 9] = [800.0, 1000.0, 1200.0, 1400.0, 1500.0, 1600.0, 1800.0, 2000.0, 2200.0];
const PSK_CAR: [&[usize]; 4] = [&[4], &[3, 5], &[2, 3, 5, 6], &[0, 1, 2, 3, 5, 6, 7, 8]];
const BPS: [(usize, usize); 3] = [(2, 2), (3, 1), (4, 1)]; // 4PSK, 8PSK, 16QAM (bits, symset)

/// One data mode: modulation, carriers, 4-FSK baud, and the per-carrier
/// `data_len` / `rs_len` from `ardopcf`'s `FrameInfo` table.
#[derive(Clone, Copy, Debug)]
pub struct Mode {
    pub ftype: u8,
    pub name: &'static str,
    /// 0 = 4PSK, 1 = 8PSK, 2 = 16QAM, 3 = 4FSK.
    pub kind: u8,
    pub carriers: usize,
    pub fsk_baud: u32,
    pub data_len: usize,
    pub rs_len: usize,
}

impl Mode {
    /// Total bytes a frame of this mode carries per carrier, FEC included.
    pub fn block(&self) -> usize {
        self.data_len + 3 + self.rs_len
    }

    /// A data frame's user bytes: every carrier's `data_len`, the count byte
    /// inside each block saying how much of it is real.
    pub fn capacity(&self) -> usize {
        self.carriers * self.data_len
    }
}

